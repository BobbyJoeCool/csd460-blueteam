        /**
         * Inserts a boat record.
         *
         * @param conn active transaction connection
         * @param boat boat being registered
         * @throws SQLException if the insert fails
         */
    private static final Set<String> EDITABLE_COLUMNS =
            Set.of(
                    "boatName",
                    "HIN",
                    "regNumber",
                    "boatType",
                    "boatBeam",
                    "boatYear"
            );

    public int insertBoat(Connection conn, Boat boat) throws SQLException {

        String sql = """
                INSERT INTO Boat (
                    boatName,
                    regNumber,
                    boatLength,
                    HIN,
                    boatType,
                    boatBeam,
                    boatYear
                )
                VALUES (?, ?, ?, ?, ?, ?, ?)
                """;

        //Insert the boat and request the generated primary key.--------------------------------------------------------------

        try (PreparedStatement stmt = conn.prepareStatement(
                sql,
                Statement.RETURN_GENERATED_KEYS)) {

        //Map the boat model values to the SQL parameters-------------------------------------------------------------------

            stmt.setString(1, boat.getBoatName());
            setNullableString(stmt, 2, boat.getRegNumber());
            stmt.setBigDecimal(3, boat.getBoatLength());
            setNullableString(stmt, 4, boat.getHIN());
            setNullableString(stmt, 5, boat.getBoatType());
            setNullableDecimal(stmt, 6, boat.getBoatBeam());
            setNullableInteger(stmt, 7, boat.getBoatYear());

            if (stmt.executeUpdate() != 1) {
                throw new SQLException(
                        "Boat registration did not insert one row.");
            }
            //Return the BoatID generated by the database 

            try (ResultSet keys = stmt.getGeneratedKeys()) {
                if (keys.next()) {
                    return keys.getInt(1);
                }
            }

            throw new SQLException(
                    "Boat registration did not return a boatID.");
        }
    }
