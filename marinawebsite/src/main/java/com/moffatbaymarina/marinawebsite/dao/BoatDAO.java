    /**
     * Connects a boat to a customer through BoatOwnership table.
     *
     * @param conn active transaction connection
     * @param boatId the ID of the boat being registered
     * @param customerId the ID of the customer who owns the boat
     * @throws SQLException if the insert fails
    */

    public void insertOwnership(
		Connection conn,
		int boatId,
		int customerId) throws SQLException {

	String sql = """
			INSERT INTO BoatOwnership (
				boatID,
				customerID,
				startDate,
				endDate
			)
			VALUES (?, ?, CURRENT_DATE, NULL)
			""";

	try (PreparedStatement stmt = conn.prepareStatement(sql)) {
		stmt.setInt(1, boatId);
		stmt.setInt(2, customerId);

		if (stmt.executeUpdate() != 1) {
			throw new SQLException(
					"Boat ownership did not insert one row.");
		}
	}
}

    /**
     * Returns  all boats currently owned by a customer. Reservation-only
     * derived values (slip size and monthly cents) are filled by the servlet;
     * checks active-reservation status for dropdown menu to prevent
     * duplicate reservations for the same boat
     */
    

    public List<Boat> findByCustomerId(
        Connection conn,
        int customerId)
        throws SQLException {

    String sql = """
            SELECT
                b.boatID,
                b.boatName,
                b.boatLength,
                EXISTS (
                    SELECT 1
                    FROM Reservation r
                    WHERE r.boatID = b.boatID
                      AND r.reservationStatus = 'Active'
                ) AS hasActiveReservation
            FROM Boat b
            JOIN BoatOwnership bo
                ON bo.boatID = b.boatID
            WHERE bo.customerID = ?
              AND bo.endDate IS NULL
            ORDER BY b.boatName
            """;

    List<Boat> boats = new ArrayList<>();

    try (PreparedStatement stmt = conn.prepareStatement(sql)) {
        stmt.setInt(1, customerId);

        try (ResultSet rs = stmt.executeQuery()) {
            while (rs.next()) {
                boats.add(mapReservationBoat(rs));
            }
        }
    }

    return boats;
}

public List<Boat> findFleetByCustomerId(
        Connection conn,
        int customerId)
        throws SQLException {

    String sql = """
            SELECT
                b.boatID,
                b.boatName,
                b.regNumber,
                b.boatLength,
                b.HIN,
                b.boatType,
                b.boatBeam,
                b.boatYear,
                r.confirmationNumber AS activeConfirmationNumber,
                r.startDate AS activeStartDate,
                d.dockNumber AS activeDockNumber,
                s.slipNumber AS activeSlipNumber
            FROM Boat b
            JOIN BoatOwnership bo
                ON bo.boatID = b.boatID
               AND bo.customerID = ?
               AND bo.endDate IS NULL
            LEFT JOIN Reservation r
                ON r.reservationID = (
                    SELECT r2.reservationID
                    FROM Reservation r2
                    WHERE r2.boatID = b.boatID
                      AND r2.reservationStatus = 'Active'
                    ORDER BY r2.startDate, r2.reservationID
                    LIMIT 1
                )
            LEFT JOIN Slip s
                ON s.slipID = r.slipID
            LEFT JOIN Dock d
                ON d.dockID = s.dockID
            ORDER BY b.boatName, b.boatID
            """;

    List<Boat> boats = new ArrayList<>();

    try (PreparedStatement stmt = conn.prepareStatement(sql)) {
        stmt.setInt(1, customerId);

        try (ResultSet rs = stmt.executeQuery()) {
            while (rs.next()) {
                boats.add(mapFleetBoat(rs));
            }
        }
    }

    return boats;
}

